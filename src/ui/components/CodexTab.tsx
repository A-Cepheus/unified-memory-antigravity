import React, { useEffect, useState } from 'react';
import type { CallToolFn, CodexBrowsePayload } from '../types.js';

interface Props {
  callTool: CallToolFn;
  defaultProjectHint?: string;
  onNotify: (msg: string, tone?: 'info' | 'success' | 'warn' | 'danger') => void;
}

function fmtBytes(b: number): string {
  return b < 1024 ? `${b} B` : `${(b / 1024).toFixed(1)} KB`;
}

export const CodexTab: React.FC<Props> = ({ callTool, defaultProjectHint, onNotify }) => {
  const [generation, setGeneration] = useState<'auto' | 'v2' | 'v1'>('auto');
  const [subView, setSubView] = useState<'summary' | 'files' | 'search'>('summary');
  const [query, setQuery] = useState('');
  const [projectHint, setProjectHint] = useState(defaultProjectHint ?? '');
  const [data, setData] = useState<CodexBrowsePayload | null>(null);
  const [loading, setLoading] = useState(false);

  const fetchCodex = async (opts?: {
    gen?: 'auto' | 'v2' | 'v1';
    q?: string;
    hint?: string;
    readGen?: 'v2' | 'v1';
    readRel?: string;
  }) => {
    setLoading(true);
    try {
      const res = await callTool<CodexBrowsePayload>('ui_browse_codex', {
        generation: opts?.gen ?? generation,
        query: opts?.q !== undefined ? opts.q : query || undefined,
        projectHint: opts?.hint !== undefined ? opts.hint : projectHint || undefined,
        readGeneration: opts?.readGen,
        readRelativePath: opts?.readRel,
      });
      setData(res);
    } catch (err) {
      onNotify(err instanceof Error ? err.message : String(err), 'danger');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchCodex({ gen: generation });
  }, [generation]);

  const handleSearch = (e: React.FormEvent) => {
    e.preventDefault();
    if (!query.trim()) return;
    setSubView('search');
    fetchCodex({ q: query.trim(), hint: projectHint.trim() });
  };

  const openFile = (gen: 'v2' | 'v1', rel: string) => {
    fetchCodex({ readGen: gen, readRel: rel });
  };

  return (
    <div>
      <div className="um-banner info">
        <span>
          <strong>Strictly Read-Only Mode:</strong> Codex memories are generated by{' '}
          <code>codex-rs/memories</code> (SQLite + internal <code>.git</code>). Writes are
          disabled to prevent consolidation conflicts.
        </span>
      </div>

      {/* Controls & Search */}
      <div className="um-card um-section">
        <div className="um-row-between" style={{ marginBottom: 10 }}>
          <div className="um-pill-bar">
            {(['auto', 'v2', 'v1'] as const).map((g) => (
              <button
                key={g}
                className={`um-pill ${generation === g ? 'active' : ''}`}
                onClick={() => setGeneration(g)}
              >
                {g === 'auto'
                  ? `Auto (${data?.status.activeGeneration ?? '...'})`
                  : g === 'v2'
                    ? `memories_v2${data?.status.v2.exists ? '' : ' (absent)'}`
                    : `memories v1${data?.status.v1.exists ? '' : ' (absent)'}`}
              </button>
            ))}
          </div>

          <div className="um-pill-bar">
            <button
              className={`um-pill ${subView === 'summary' ? 'active' : ''}`}
              onClick={() => setSubView('summary')}
            >
              Summary
            </button>
            <button
              className={`um-pill ${subView === 'files' ? 'active' : ''}`}
              onClick={() => setSubView('files')}
            >
              Files ({data?.files.length ?? 0})
            </button>
            <button
              className={`um-pill ${subView === 'search' ? 'active' : ''}`}
              onClick={() => setSubView('search')}
            >
              Search ({data?.hits.length ?? 0})
            </button>
          </div>
        </div>

        <form className="um-row" onSubmit={handleSearch}>
          <input
            className="um-input"
            style={{ flex: 2, minWidth: 160 }}
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            placeholder="Search rollouts, extensions/ad_hoc, v1 MEMORY.md..."
          />
          <input
            className="um-input"
            style={{ flex: 1, minWidth: 120 }}
            value={projectHint}
            onChange={(e) => setProjectHint(e.target.value)}
            placeholder="Project boost (optional)"
          />
          <button type="submit" className="um-btn primary" disabled={loading || !query.trim()}>
            Search
          </button>
        </form>
      </div>

      {/* Inline File Reader */}
      {data?.fileContent && (
        <div className="um-card um-section">
          <div className="um-card-header">
            <div className="um-row">
              <span className="um-badge info">{data.fileContent.generation}</span>
              <span className="um-mono">{data.fileContent.relativePath}</span>
              <span className="um-muted">{fmtBytes(data.fileContent.totalBytes)}</span>
              {data.fileContent.truncated && <span className="um-badge warn">Truncated</span>}
            </div>
            <button className="um-btn sm" onClick={() => setData({ ...data, fileContent: null })}>
              Close Viewer
            </button>
          </div>
          <pre className="um-pre">{data.fileContent.content}</pre>
        </div>
      )}

      {/* Subview: Summary */}
      {subView === 'summary' && data && (
        <div className="um-card um-section">
          <div className="um-card-header">
            <div className="um-row">
              <h3 className="um-card-title">memory_summary.md</h3>
              <span className="um-badge success">{data.summary.generation}</span>
              <span className="um-muted">{fmtBytes(data.summary.totalBytes)}</span>
            </div>
            <button className="um-btn sm" onClick={() => fetchCodex()} disabled={loading}>
              Refresh
            </button>
          </div>
          {data.summary.content ? (
            <pre className="um-pre" style={{ maxHeight: 460 }}>
              {data.summary.content}
            </pre>
          ) : (
            <div className="um-empty">No memory_summary.md found in this generation.</div>
          )}
        </div>
      )}

      {/* Subview: Files */}
      {subView === 'files' && data && (
        <div className="um-card um-section">
          <div className="um-card-header">
            <h3 className="um-card-title">
              Files in {data.selectedGeneration === 'v2' ? 'memories_v2' : 'memories'} (
              {data.files.length})
            </h3>
          </div>
          {data.files.length === 0 ? (
            <div className="um-empty">No readable markdown files found.</div>
          ) : (
            <div className="um-list">
              {data.files.map((f) => (
                <div
                  key={f.relativePath}
                  className="um-item um-item-hover"
                  onClick={() => openFile(data.selectedGeneration, f.relativePath)}
                >
                  <div className="um-row-between">
                    <div className="um-row">
                      <span className="um-badge info">{f.category}</span>
                      <span className="um-mono">{f.relativePath}</span>
                    </div>
                    <span className="um-muted">{fmtBytes(f.sizeBytes)}</span>
                  </div>
                </div>
              ))}
            </div>
          )}
        </div>
      )}

      {/* Subview: Search Hits */}
      {subView === 'search' && data && (
        <div className="um-card um-section">
          <div className="um-card-header">
            <h3 className="um-card-title">Search Results ({data.hits.length})</h3>
          </div>
          {data.hits.length === 0 ? (
            <div className="um-empty">
              Enter keywords above and click Search to query across Codex v2 + v1 memories.
            </div>
          ) : (
            <div className="um-list">
              {data.hits.map((hit, i) => (
                <div
                  key={`${hit.generation}-${hit.relativePath}-${i}`}
                  className="um-item um-item-hover"
                  onClick={() => openFile(hit.generation, hit.relativePath)}
                >
                  <div className="um-row-between">
                    <div className="um-row">
                      <span className="um-badge success">{hit.generation}</span>
                      <span className="um-badge info">{hit.category}</span>
                      <strong>{hit.title}</strong>
                    </div>
                    <span className="um-muted">score {hit.score}</span>
                  </div>
                  <div className="um-muted" style={{ marginTop: 4 }}>
                    {hit.snippet}
                  </div>
                  <div className="um-mono um-muted" style={{ marginTop: 4 }}>
                    {hit.relativePath}
                  </div>
                </div>
              ))}
            </div>
          )}
        </div>
      )}
    </div>
  );
};
